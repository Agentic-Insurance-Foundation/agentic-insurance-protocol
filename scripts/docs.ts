// Writes the parts of docs/, the Mintlify site, that come from the source: the
// types, the examples and the files of the AIP skill. The pages in docs/ are MDX
// written by hand, except the schema reference and the page of each country
// file, which this script writes in full. A page written by hand imports the
// tables and lists of snippets/generated/ and the JSON of snippets/examples/.
// The script fails when a page names a type that schema.json does not define,
// or when docs.json leaves a page out.
import { copyFileSync, mkdirSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { REGISTRY_ERRORS, REGISTRY_TOOLS, type RegistryToolName } from "@spec/registry";
import { PROTOCOL_VERSION, TOOL_ERRORS, TOOLS, type ConformanceLevel, type ToolName } from "@spec/schema";
import { readRepoFile, readRepoJson } from "@/website/lib/repo-files";
import { SITE_URL, repoFileUrl } from "@/website/lib/site";
import { countryFiles, SKILL_FILE_PATH, skillManifest, skillNever, skillSteps, type CountryFile, type RulesFile } from "@/website/lib/skill-content";
import { countryRuleName, evalCases, sectionItems, SPEC_FILES } from "./evals";
import { EXAMPLES_DIR } from "./example-files";

const root = join(import.meta.dir, "..");
const docs = join(root, "docs");

// The address of each page, from the root of the docs. Mintlify serves the
// docs under /docs, and adds that part itself.
const PAGES = {
  spec: `/${PROTOCOL_VERSION}/spec`,
  registry: `/${PROTOCOL_VERSION}/registry`,
  reference: `/${PROTOCOL_VERSION}/reference`,
  skill: `/${PROTOCOL_VERSION}/skill`,
};

const GENERATED = "{/* Generated by scripts/docs.ts. Don't edit it by hand. */}";

/**
 * The anchor that Mintlify gives a heading: lower case, without commas,
 * brackets or backticks, and one dash for each run of spaces, dots and colons.
 * Mintlify keeps other punctuation, so a heading with it fails here.
 */
function slug(heading: string): string {
  if (!/^[\w\s.,:()`-]+$/.test(heading)) throw new Error(`The anchor of the heading "${heading}" is not known`);
  return heading
    .toLowerCase()
    .replace(/[,()`]/g, "")
    .replace(/[\s.:]+/g, "-")
    .replace(/^-|-$/g, "");
}

/** Escapes the characters that MDX reads as JSX, outside inline code. */
function mdx(text: string): string {
  const escapes: Record<string, string> = { "{": "&#123;", "}": "&#125;", "<": "&lt;" };
  return text
    .split(/(`[^`\n]*`)/)
    .map((part, index) => (index % 2 ? part : part.replace(/[{}<]/g, (char) => escapes[char] ?? char)))
    .join("");
}

/** Escapes a Markdown text line by line, outside code blocks. */
function mdxBlock(markdown: string): string {
  let inCode = false;
  return markdown
    .split("\n")
    .map((line) => {
      if (line.startsWith("```")) inCode = !inCode;
      return inCode || line.startsWith("```") ? line : mdx(line);
    })
    .join("\n");
}

const definitions = schemaDefinitions();
const typeNames = new Set(Object.keys(definitions));

function typeAnchor(name: string): string {
  return slug(name);
}

/** Links each type that inline code names, such as `Offer` or `AipSettings.lines`, to its definition. */
function linkTypes(markdown: string, reference = PAGES.reference): string {
  return markdown.replace(/(?<!\[)`([A-Z][A-Za-z0-9]*)((?:\.\w+)*)`(?!\]\()/g, (code, name: string) =>
    typeNames.has(name) ? `[${code}](${reference}#${typeAnchor(name)})` : code,
  );
}

function typeLink(name: string, reference = PAGES.reference): string {
  return `[\`${name}\`](${reference}#${typeAnchor(name)})`;
}

function cell(text: string): string {
  return text.replace(/\s*\n\s*/g, " ").replace(/\|/g, "\\|");
}

function table(head: string[], rows: string[][]): string {
  return [
    `| ${head.join(" | ")} |`,
    `|${head.map(() => "---").join("|")}|`,
    ...rows.map((row) => `| ${row.map(cell).join(" | ")} |`),
  ].join("\n");
}

function write(path: string, text: string): void {
  const full = join(docs, path);
  mkdirSync(dirname(full), { recursive: true });
  writeFileSync(full, `${text.trimEnd()}\n`);
}

function frontMatter(fields: Record<string, string>): string {
  return ["---", ...Object.entries(fields).map(([key, value]) => `${key}: ${JSON.stringify(value)}`), "---"].join("\n");
}

/* Source files of the spec */

/** The subset of JSON Schema that schema.json uses. */
interface JsonSchema {
  $ref?: string;
  type?: string | string[];
  description?: string;
  properties?: Record<string, JsonSchema>;
  required?: string[];
  items?: JsonSchema;
  anyOf?: JsonSchema[];
  enum?: unknown[];
  const?: unknown;
  format?: string;
  pattern?: string;
  additionalProperties?: boolean | JsonSchema;
}

function schemaDefinitions(): Record<string, JsonSchema> {
  return readRepoJson<{ definitions: Record<string, JsonSchema> }>("spec/schema.json").definitions;
}

interface SchemaSection {
  number: number;
  title: string;
  /** Exported type names, in file order. */
  types: string[];
}

/** The files that hold the types, in the order of the schema reference. */
type TypeSource = "spec/schema.ts" | "registry/src/schema.ts";

/** The numbered sections of a source file, each with the types it exports. */
function schemaSections(file: TypeSource = "spec/schema.ts"): SchemaSection[] {
  const sections: SchemaSection[] = [];
  for (const line of readRepoFile(file).split("\n")) {
    const header = /^\/\* (\d+)\. (.+?)\s*\*\/$/.exec(line);
    if (header?.[1] && header[2]) {
      sections.push({ number: Number(header[1]), title: header[2], types: [] });
      continue;
    }
    const declaration = /^export (?:interface|type) (\w+)/.exec(line);
    const current = sections.at(-1);
    if (declaration?.[1] && current) current.types.push(declaration[1]);
  }
  return sections;
}

/** Text of the declaration of schema.ts that starts with `start`, up to the first line that is exactly `end`. */
function declarationBlock(start: string, end: string): string {
  const source = readRepoFile("spec/schema.ts");
  const from = source.indexOf(start);
  if (from < 0) throw new Error(`schema.ts has no "${start}"`);
  const to = source.indexOf(`\n${end}\n`, from);
  return source.slice(from, to < 0 ? undefined : to);
}

/** Params and result type of each tool, from `ToolSignatures`. */
function toolSignatures(): Record<string, { params: string; result: string }> {
  const signatures: Record<string, { params: string; result: string }> = {};
  const block = declarationBlock("interface ToolSignatures", "}");
  for (const match of block.matchAll(/^\s+(\w+): \{ params: (\w+); result: (\w+) \};$/gm)) {
    if (match[1] && match[2] && match[3]) signatures[match[1]] = { params: match[2], result: match[3] };
  }
  return signatures;
}

/** The name of each conformance level, from the comment on `ConformanceLevel`. */
function levelNames(): Record<number, string> {
  const source = readRepoFile("spec/schema.ts");
  const comment = source.slice(0, source.indexOf("type ConformanceLevel"));
  const names: Record<number, string> = {};
  for (const match of comment.slice(comment.lastIndexOf("/**")).matchAll(/^ \* - (\d) (\w+):/gm)) {
    if (match[1] && match[2]) names[Number(match[1])] = match[2];
  }
  return names;
}

/** Each error code with the comment above it in `AipErrorCode`. */
function errorCodes(): { code: string; meaning: string }[] {
  const name = "AipErrorCode";
  const block = declarationBlock(`type ${name} =`, "");
  const codes: { code: string; meaning: string }[] = [];
  let comment = "";
  for (const line of block.split("\n")) {
    const doc = /^\s*\/\*\*\s*(.+?)\s*\*\/$/.exec(line);
    if (doc?.[1]) {
      comment = doc[1];
      continue;
    }
    if (/^\s*\/\*\*/.test(line)) throw new Error(`${name} comments must fit on one line`);
    const member = /^\s*\|\s*"(\w+)"/.exec(line);
    if (member?.[1]) {
      if (!comment) throw new Error(`${name} "${member[1]}" has no comment`);
      codes.push({ code: member[1], meaning: comment });
      comment = "";
    }
  }
  return codes;
}

/* Tables of the specification */

const toolNames = Object.keys(TOOLS) as ToolName[];

function levelsTable(): string {
  const names = levelNames();
  const levels = [...new Set(toolNames.map((tool) => TOOLS[tool].level))].sort() as ConformanceLevel[];
  return table(
    ["Level", "Adds the tools"],
    levels.map((level) => {
      const tools = toolNames.filter((tool) => TOOLS[tool].level === level);
      return [`${level}. ${names[level] ?? ""}`, tools.map((tool) => `\`${tool}\``).join(", ")];
    }),
  );
}

function toolsTable(): string {
  const signatures = toolSignatures();
  return table(
    ["Tool", "Level", "Effect", "Params → result"],
    toolNames.map((tool) => {
      const { level, readOnlyHint } = TOOLS[tool];
      const signature = signatures[tool];
      if (!signature) throw new Error(`ToolSignatures has no entry for ${tool}`);
      return [`\`${tool}\``, String(level), readOnlyHint ? "Read-only" : "Starts an application", `${typeLink(signature.params)} → ${typeLink(signature.result)}`];
    }),
  );
}

function errorsTable(): string {
  return table(
    ["Code", "Meaning"],
    errorCodes().map(({ code, meaning }) => [`\`${code}\``, linkTypes(mdx(meaning))]),
  );
}

function toolErrorsTable(): string {
  return table(
    ["Tool", "Errors of this tool"],
    toolNames.map((tool) => [`\`${tool}\``, TOOL_ERRORS[tool].map((code) => `\`${code}\``).join(", ") || "None"]),
  );
}

const registryToolNames = Object.keys(REGISTRY_TOOLS) as RegistryToolName[];

function registryToolsTable(): string {
  return table(
    ["Tool", "Params → result"],
    registryToolNames.map((tool) => {
      const type = tool.replace(/(^|_)([a-z])/g, (_, __, letter: string) => letter.toUpperCase());
      return [`\`${tool}\``, `${typeLink(`${type}Params`)} → ${typeLink(`${type}Result`)}`];
    }),
  );
}

function registryErrorsTable(): string {
  return table(
    ["Code", "Meaning"],
    Object.entries(REGISTRY_ERRORS).map(([code, meaning]) => [`\`${code}\``, linkTypes(mdx(meaning))]),
  );
}

/* Tables of the evaluation */

const SPEC_PAGES: Record<string, string> = { AIP: PAGES.spec, Registry: PAGES.registry };

/** A rule that a test case names, as a link to its section, or to the page of its country file. */
function ruleLink(rule: string): string {
  const spec = /^(AIP|Registry) (\d+(?:\.\d+)?)$/.exec(rule);
  if (spec?.[1] && spec[2]) {
    const file = SPEC_FILES[spec[1]];
    const heading = file && new RegExp(`^#{2,3} (${spec[2].replace(".", "\\.")}\\.? .+)$`, "m").exec(readRepoFile(file))?.[1];
    if (!heading) throw new Error(`evals.json: no section for the rule "${rule}"`);
    return `[${rule}](${SPEC_PAGES[spec[1]]}#${slug(heading)})`;
  }
  const code = /^([a-z]{2})\//.exec(rule)?.[1];
  return `[${rule}](${code ? `${PAGES.skill}/${code}` : PAGES.skill})`;
}

const regionNames = new Intl.DisplayNames(["en"], { type: "region" });

function evalCasesTable(): string {
  return table(
    ["Case", "Country", "Risk", "Rules it tests"],
    evalCases().map((item) => [
      `${item.id}. \`${item.name}\``,
      regionNames.of(item.country) ?? item.country,
      mdx(item.risk),
      item.rules.map(ruleLink).join("; "),
    ]),
  );
}

function evalCoverageTable(): string {
  const named = new Set(evalCases().flatMap((item) => item.rules));
  const files = countryFiles().flatMap((country) => [country, ...country.extraFiles].map((file) => ({ file, code: country.code })));
  return table(
    ["Rules file", "Owner", "Rules", "With a test case"],
    files.map(({ file, code }) => {
      const path = file.path.replace(/^.*\/references\/countries\//, "");
      const headings = [...file.body.matchAll(/^## (.+)$/gm)].map((match) => match[1] ?? "");
      let count = 0;
      const tested = headings.flatMap((heading) => {
        const numbers = (sectionItems(file.body, heading) ?? [])
          .map((_, index) => index + 1)
          .filter((number) => named.has(countryRuleName(path, heading, number)));
        count += numbers.length;
        return numbers.length ? [`${heading} ${numbers.join(", ")}`] : [];
      });
      return [`[${path}](${PAGES.skill}/${code})`, file.owner, String(file.rules), count ? `${count}: ${tested.join("; ")}` : "None"];
    }),
  );
}

