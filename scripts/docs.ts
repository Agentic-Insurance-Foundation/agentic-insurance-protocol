/* Schema reference */

function refName(ref: string): string {
  return decodeURIComponent(ref.replace("#/definitions/", ""));
}

function typeLabel(schema: JsonSchema): string {
  if (schema.$ref) return typeLink(refName(schema.$ref), "");
  if (schema.anyOf) return schema.anyOf.map(typeLabel).join(" or ");
  if (schema.enum) return `one of ${schema.enum.map((value) => `\`${String(value)}\``).join(", ")}`;
  if (schema.const !== undefined) return `\`${String(schema.const)}\``;
  const type = Array.isArray(schema.type) ? schema.type.join(" or ") : schema.type;
  if (type === "array") return `list of ${schema.items ? typeLabel(schema.items) : "any"}`;
  if (type === "object") {
    if (schema.properties) return `object with ${Object.keys(schema.properties).map((key) => `\`${key}\``).join(", ")}`;
    if (typeof schema.additionalProperties === "object") return `map of ${typeLabel(schema.additionalProperties)}`;
    return "object";
  }
  if (!type) return "any";
  return schema.format ? `${type} (${schema.format})` : type;
}

function description(text: string | undefined): string {
  return text ? linkTypes(mdxBlock(text), "") : "";
}

function fieldsTable(schema: JsonSchema): string {
  const required = new Set(schema.required ?? []);
  return table(
    ["Field", "Type", "Required", "Description"],
    Object.entries(schema.properties ?? {}).map(([key, property]) => [
      `\`${key}\``,
      typeLabel(property),
      required.has(key) ? "Yes" : "",
      description(property.description),
    ]),
  );
}

function variantLabel(variant: JsonSchema, index: number): string {
  const discriminant = Object.entries(variant.properties ?? {}).find(([, property]) => property.const !== undefined);
  return discriminant ? `\`${discriminant[0]}: ${String(discriminant[1].const)}\`` : `Variant ${index + 1}`;
}

function definitionBody(schema: JsonSchema): string {
  if (schema.properties) return fieldsTable(schema);
  if (schema.anyOf?.every((variant) => variant.properties)) {
    return schema.anyOf.map((variant, index) => `**${variantLabel(variant, index)}**\n\n${fieldsTable(variant)}`).join("\n\n");
  }
  const facts = [`Type: ${typeLabel(schema)}.`];
  if (schema.pattern) facts.push(`Pattern: \`${schema.pattern}\`.`);
  return facts.join(" ");
}

function referencePage(): string {
  const placed = new Set<string>();
  // The registry sections come after the sections of schema.ts, numbered R1, R2…
  const sources: { file: TypeSource; prefix: string }[] = [
    { file: "spec/schema.ts", prefix: "" },
    { file: "registry/src/schema.ts", prefix: "R" },
  ];
  const sections = sources.flatMap(({ file, prefix }) =>
    schemaSections(file).map((section) => {
      const names = section.types.flatMap((type) => [...typeNames].filter((name) => !placed.has(name) && (name === type || name.startsWith(`${type}<`))));
      names.forEach((name) => placed.add(name));
      const body = names
        .map((name) => [`### \`${name}\``, description(definitions[name]?.description), definitionBody(definitions[name] ?? {})].filter(Boolean).join("\n\n"))
        .join("\n\n");
      return `## ${prefix}${section.number}. ${section.title}\n\n${body || "No types."}`;
    }),
  );
  const unplaced = [...typeNames].filter((name) => !placed.has(name));
  if (unplaced.length) throw new Error(`Definitions with no section in spec/schema.ts or registry/src/schema.ts: ${unplaced.join(", ")}`);
  return [
    frontMatter({
      title: "Schema reference",
      description: "Every type of AIP, generated from spec/schema.ts and registry/src/schema.ts.",
    }),
    GENERATED,
    `Every type of AIP draft ${PROTOCOL_VERSION}, generated from [\`spec/schema.ts\`](${repoFileUrl("spec/schema.ts")}) and the registry server's [\`registry/src/schema.ts\`](${repoFileUrl("registry/src/schema.ts")}) through [\`schema.json\`](${SITE_URL}/schemas/${PROTOCOL_VERSION}/schema.json). The sections follow \`spec/schema.ts\`, then \`registry/src/schema.ts\` from R1. The rules in the descriptions use the RFC 2119 keywords.`,
    ...sections,
  ].join("\n\n");
}

/* The AIP skill */

function status(file: RulesFile): string {
  return file.status === "endorsed" ? `Endorsed by ${file.endorsedBy}` : "Draft";
}

function skillVersion(): string {
  const manifest = skillManifest();
  return `Version \`${manifest.version}\` of the skill, for ${manifest.protocol}. [Get SKILL.md](${SITE_URL}/${SKILL_FILE_PATH})`;
}

/** The steps of the procedure in guidelines.md. */
function skillStepList(): string {
  const steps = skillSteps().map((step) => `<Step title={${JSON.stringify(step.title)}}>\n\n${linkTypes(mdx(step.text))}\n\n</Step>`);
  return `<Steps>\n${steps.join("\n")}\n</Steps>`;
}

/** The Never list of guidelines.md. */
function skillNeverList(): string {
  return skillNever()
    .map((rule) => `- ${linkTypes(mdx(rule))}`)
    .join("\n");
}

function skillCountriesTable(): string {
  return table(
    ["Country", "Status", "Version", "Owner", "Rules", "Last legal review"],
    countryFiles().map((file) => [
      `[${file.name}](${PAGES.skill}/${file.code})`,
      status(file),
      `\`${file.version}\``,
      file.owner,
      `${file.rules}, ${file.notReviewed} not reviewed`,
      file.reviewedAt ?? "None yet",
    ]),
  );
}

function countryPage(file: CountryFile): string {
  const body = file.body.slice(file.body.indexOf("\n") + 1).trim();
  const extra = file.extraFiles.map(
    (more) =>
      `- [${more.name}](${SITE_URL}/skills/${more.path}): version \`${more.version}\`, ${status(more).toLowerCase()}, ${more.rules} rules, ${more.notReviewed} not reviewed`,
  );
  return [
    frontMatter({
      title: file.name,
      description: `The rules that an AI agent follows to buy insurance for a customer in ${file.name}, with the legal source of each rule.`,
    }),
    GENERATED,
    table(
      ["Status", "Version", "Owner", "Last legal review", "Rules"],
      [[status(file), `\`${file.version}\``, file.owner, file.reviewedAt ?? "None yet", `${file.rules}, ${file.notReviewed} not reviewed`]],
    ),
    `[Take over this file](${PAGES.skill}#take-over-a-country-file) · [View as Markdown](${SITE_URL}/skills/${file.path})`,
    linkTypes(mdxBlock(body)),
    ...(extra.length
      ? ["## Files for a state or a line", "The AI agent follows each of these files as well as the country file, when it applies.", extra.join("\n")]
      : []),
    "## Legal sources",
    file.sources.map((source) => `- [${mdx(source.title)}](${source.url})`).join("\n"),
  ].join("\n\n");
}

/* Checks */

/** The pages of docs/, as Mintlify names them: the path without the extension. */
function pageFiles(dir = docs): string[] {
  return readdirSync(dir).flatMap((entry) => {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) return entry === "snippets" || entry === "node_modules" ? [] : pageFiles(full);
    return entry.endsWith(".mdx") ? [relative(docs, full).replace(/\.mdx$/, "")] : [];
  });
}

function navigationPages(node: unknown): string[] {
  if (typeof node === "string") return [node];
  if (Array.isArray(node)) return node.flatMap(navigationPages);
  if (node && typeof node === "object") return Object.entries(node).flatMap(([key, value]) => (["pages", "groups", "tabs", "versions"].includes(key) ? navigationPages(value) : []));
  return [];
}

/** Each page is in the navigation of docs.json. */
function checkNavigation(): void {
  const listed = new Set(navigationPages(readRepoJson<{ navigation: unknown }>("docs/docs.json").navigation));
  const missing = pageFiles().filter((page) => !listed.has(page));
  if (missing.length) throw new Error(`docs/docs.json leaves out the pages ${missing.join(", ")}`);
}

/** Inline code that looks like a type, such as `Offer` or `Offer.premium`, names a type of schema.json. */
function checkTypes(): void {
  const problems: string[] = [];
  for (const page of pageFiles()) {
    const text = readRepoFile(`docs/${page}.mdx`).replace(/^```[\s\S]*?^```/gm, "");
    for (const match of text.matchAll(/`([A-Z][A-Za-z0-9]*)(?:\.\w+)*`/g)) {
      if (match[1] && !typeNames.has(match[1])) problems.push(`${page}: ${match[0]}`);
    }
  }
  if (problems.length) throw new Error(`The docs name types that schema.json does not define:\n${problems.join("\n")}`);
}

